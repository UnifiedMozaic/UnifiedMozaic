static const double um_f4_mag[8] = {0.0, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0};

// 大きさ a（0 以上、NaN でない）に最も近い値の番号を返す。mag は小さい順に n 個。
static unsigned um_small_nearest(const double *mag, unsigned n, double a) {
  unsigned lo = 0;
  while (lo + 1 < n && mag[lo + 1] <= a) lo++;
  if (lo + 1 == n) return lo; // 最大値以上は飽和
  double mid = (mag[lo] + mag[lo + 1]) / 2; // 正確に表せる
  if (a < mid) return lo;
  if (a > mid) return lo + 1;
  return (lo & 1) ? lo + 1 : lo; // ちょうど中間: 偶数の方
}

unsigned char um_f8_enc(double v) {
  if (v != v) return 0x7f;
  unsigned char sign = 0;
  if (v < 0 || (v == 0 && 1 / v < 0)) {
    sign = 0x80;
    v = -v;
  }
  return sign | (unsigned char)um_small_nearest(um_f8_mag, 127, v);
}

unsigned char um_f4_enc(double v) {
  if (v != v) return 0;
  unsigned char sign = 0;
  if (v < 0 || (v == 0 && 1 / v < 0)) {
    sign = 8;
    v = -v;
  }
  return sign | (unsigned char)um_small_nearest(um_f4_mag, 8, v);
}
